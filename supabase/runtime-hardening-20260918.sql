create or replace function private.protect_profile_entitlements()
returns trigger language plpgsql security definer set search_path to 'pg_catalog','public'
as $$
declare v_uid uuid:=auth.uid(); v_is_admin boolean:=false; v_trial_days integer:=30; v_has_profile boolean:=false;
begin
 if v_uid is null then return new; end if;
 select exists(select 1 from public.admin_users a where a.user_id=v_uid) into v_is_admin;
 if v_is_admin then return new; end if;
 if tg_op='INSERT' then
   select coalesce(trial_days,30) into v_trial_days from public.business_settings where id='main';
   select exists(select 1 from public.profiles p where p.user_id=v_uid or p.created_by=v_uid) into v_has_profile;
   new.user_id:=v_uid; new.created_by:=v_uid; new.status:='trial'; new.current_period_end:=null;
   new.trial_ends_at:=case when v_has_profile then now() else now()+make_interval(days=>greatest(0,least(v_trial_days,365))) end;
   return new;
 end if;
 if new.user_id is distinct from old.user_id or new.created_by is distinct from old.created_by or new.status is distinct from old.status or new.trial_ends_at is distinct from old.trial_ends_at or new.current_period_end is distinct from old.current_period_end then
  raise exception 'No puedes modificar propiedad, plan o vigencia de la tarjeta.' using errcode='42501';
 end if;
 return new;
end; $$;
revoke all on function private.protect_profile_entitlements() from public,anon,authenticated;

drop trigger if exists protect_profile_entitlements on public.profiles;
create trigger protect_profile_entitlements before insert or update on public.profiles for each row execute function private.protect_profile_entitlements();

