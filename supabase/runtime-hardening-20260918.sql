with ranked as (
  select id,row_number() over(order by created_at,id) rn from public.payments where sequence_no is null
)
update public.payments p set sequence_no=r.rn from ranked r where p.id=r.id;
select setval('private.payment_sequence',greatest(coalesce((select max(sequence_no) from public.payments),0),1),true);
alter table public.payments alter column sequence_no set not null;
